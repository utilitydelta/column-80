// session-v43 phase 3: ONE LIVE GENERATION through the product on the
// `claude-code` backend, end to end - real extension host, real settings, real
// `claude` CLI, real subscription. Everything below this tier is already
// unit-proven against a fake CLI shim; this file exists because a fake shim
// cannot tell you the real CLI still answers the way the recorded payload says
// it does.
//
// IT SPENDS REAL SUBSCRIPTION QUOTA - roughly 26-40k tokens of harness startup
// context per call on top of the prompt, measured on claude 2.1.224. One
// generation, once. It is gated on C80_CLAUDE_LIVE=1 so a normal
// `npm run test:vscode` never bills anyone by accident.
//
// Run (the reference box has a display on :1; see .vscode-test.mjs for why
// test:vscode:ci does not work here):
//
//   C80_CLAUDE_LIVE=1 DISPLAY=:1 npx vscode-test --config test-vscode/.vscode-test.mjs --label ts
//
// What it proves, and why each one needed a LIVE round rather than a shim:
//   - the settings enum value actually resolves to this backend in a real host
//   - the CLI is spawned in the product-owned neutral cwd, not the workspace
//   - the real CLI's JSON still maps (the fence strip fires on a real reply)
//   - the evidence line the human reads is the one the module promises
//   - what the neutral cwd holds afterwards (scraps S43-5's open question)

'use strict';

const assert = require('assert');
const vscode = require('vscode');
const fs = require('fs');
const os = require('os');
const path = require('path');

const LIVE = process.env.C80_CLAUDE_LIVE === '1';
// The model the live round asks for. Overridable so a future run can price a
// different one without editing the file.
const LIVE_MODEL = process.env.C80_CLAUDE_MODEL || 'claude-sonnet-4-5';
const EXT_ID = 'utilitydelta.column-80';

// Same instrument as v33: the channel tee is read out of the environment when
// the extension ACTIVATES, so both facts are captured at module load. A missing
// instrument read as a measurement is the failure this comment exists to stop.
const extensionAtLoad = vscode.extensions.getExtension(EXT_ID);
const ACTIVE_AT_LOAD = extensionAtLoad ? extensionAtLoad.isActive === true : false;
const LOG_FROM_ENV = typeof process.env.C80_LOG_FILE === 'string' && process.env.C80_LOG_FILE !== '';
const DEFAULT_LOG = path.join(os.tmpdir(), `c80-v43-live-${process.pid}.log`);
if (!LOG_FROM_ENV) {
  process.env.C80_LOG_FILE = DEFAULT_LOG;
}
const LOG_FILE = process.env.C80_LOG_FILE;
const NO_INSTRUMENT = !LOG_FROM_ENV && ACTIVE_AT_LOAD;

const logMark = () => {
  try {
    return fs.statSync(LOG_FILE).size;
  } catch {
    return 0;
  }
};
const logSince = (mark) => {
  try {
    return fs.readFileSync(LOG_FILE).subarray(mark).toString('utf8');
  } catch {
    return '';
  }
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// The evidence this session is actually about, in the order a reader meets it.
const carveLine = (text) => /^\[carve\] tier=claude-code .*$/m.exec(text);
const roundLine = (text) => /^\[claude-code\] .*$/m.exec(text);

const TARGET_REL = 'playground/c80_v43_claude.ts';
const TARGET_TEXT = `// Column 80 session-v43 live target. Regenerated by the test; safe to delete.

/** Adds two numbers and returns the sum. */
export function v43Add(a: number, b: number): number {
  return 0;
}
`;

suite('session-v43: claude-code backend, live through the product', () => {
  let repo;
  let targetUri;
  let priorModel;

  suiteSetup(async function () {
    if (!LIVE) {
      return;
    }
    this.timeout(120000);
    const folders = vscode.workspace.workspaceFolders;
    assert.ok(folders && folders.length > 0, 'the tier must run rooted at a workspace folder');
    repo = folders[0].uri.fsPath;

    targetUri = vscode.Uri.file(path.join(repo, TARGET_REL));
    fs.mkdirSync(path.dirname(targetUri.fsPath), { recursive: true });
    fs.writeFileSync(targetUri.fsPath, TARGET_TEXT);

    // The provider switch is the whole point: flip the real setting, in the
    // real host, and let the extension rebuild its service the way it would for
    // a user who picked it in the settings UI.
    const cfg = vscode.workspace.getConfiguration('column80');
    priorModel = cfg.inspect('fnGenModel')?.globalValue;
    await cfg.update('fnGenProvider', 'claude-code', vscode.ConfigurationTarget.Global);
    // A Claude model id, because the setting still holds the local ollama tag
    // by default. Set BEFORE the provider settles so one rebuild covers both.
    await cfg.update('fnGenModel', LIVE_MODEL, vscode.ConfigurationTarget.Global);

    const ext = vscode.extensions.getExtension(EXT_ID);
    assert.ok(ext, 'the extension must be present in the host');
    await ext.activate();
    // The service rebuild is debounced behind the config-change event; give it
    // room rather than racing it.
    await sleep(3000);
  });

  suiteTeardown(async () => {
    if (!LIVE) {
      return;
    }
    const cfg = vscode.workspace.getConfiguration('column80');
    await cfg.update('fnGenProvider', undefined, vscode.ConfigurationTarget.Global);
    // Put the model back. vscode-test keeps its user-data-dir between runs, so
    // a setting left behind here is a setting the NEXT run inherits - which is
    // exactly how this file's first version came to pass once and then fail.
    await cfg.update('fnGenModel', priorModel, vscode.ConfigurationTarget.Global);
    try {
      fs.rmSync(targetUri.fsPath, { force: true });
    } catch {
      /* the target is disposable by construction */
    }
  });

  test('the carve line names the claude-code tier and fn-gen is ENABLED', async function () {
    if (!LIVE) {
      this.skip();
    }
    if (NO_INSTRUMENT) {
      assert.fail('no channel instrument: set C80_LOG_FILE before the host starts');
    }
    this.timeout(60000);
    // Read the WHOLE log, not a slice since a mark. An earlier version forced a
    // rebuild by writing the model setting and then read only what followed -
    // which passed once and failed on the next run, because vscode-test keeps
    // its user-data-dir between runs, the setting was already that value, no
    // config-change event fired, and no new line was written. A test that
    // depends on a change being a change is a test that passes only on a clean
    // profile. suiteSetup has already put the provider in place; the line is
    // there whether this run wrote it or the rebuild at activation did.
    const text = logSince(0);
    const line = carveLine(text);
    assert.ok(line, `expected a [carve] tier=claude-code line, got:\n${text.slice(0, 2000)}`);
    assert.ok(
      /fnGen=enabled/.test(line[0]),
      `fn-gen must be ENABLED on this box (the claude CLI is installed): ${line[0]}`
    );
    console.log(`[v43 evidence] ${line[0]}`);
  });

  test('ONE live generation: the round completes and the evidence line is the promised shape', async function () {
    if (!LIVE) {
      this.skip();
    }
    // A live claude round is ~15s on a realistic prompt, plus a cold-start
    // first call of ~9s. This budget is slack, not a deadline.
    this.timeout(300000);

    const doc = await vscode.workspace.openTextDocument(targetUri);
    const editor = await vscode.window.showTextDocument(doc, { preview: false });
    const idx = doc.getText().indexOf('return 0;');
    assert.ok(idx > 0, 'the target body must be findable');
    editor.selection = new vscode.Selection(doc.positionAt(idx), doc.positionAt(idx));

    const mark = logMark();
    // Fire and watch the channel rather than awaiting: a failed round ends on
    // an AWAITED error toast, whose promise never settles until someone
    // dismisses it (the trap recorded in .vscode-test.mjs).
    void vscode.commands.executeCommand('column80.generateFunction');

    const deadline = Date.now() + 240000;
    let round;
    while (Date.now() < deadline) {
      round = roundLine(logSince(mark));
      if (round) {
        break;
      }
      await sleep(1000);
    }
    const text = logSince(mark);
    assert.ok(round, `no [claude-code] round line within the budget. Channel said:\n${text.slice(0, 4000)}`);
    console.log(`[v43 evidence] ${round[0]}`);

    assert.ok(
      /round=failed/.test(round[0]) === false,
      `the live round FAILED: ${round[0]}\nchannel:\n${text.slice(0, 4000)}`
    );
    // The promised shape, field by field. `fence-strip` is the one this whole
    // backend exists for: the real CLI fences its replies despite being told
    // not to, and an unstripped reply is rejected wholesale downstream.
    for (const field of [/fence-strip=(yes|no)/, /num_turns=\d+/, /model=\S+/, /ttft=\d+ms/, /total=\d+ms/, /cli-ttft=-?\d+ms/, /cli-total=-?\d+ms/]) {
      assert.ok(field.test(round[0]), `evidence line is missing ${field}: ${round[0]}`);
    }
    // Wall clock vs the CLI's self-report (amendment B4): they must not be the
    // same number, because the CLI's excludes the spawn, the boot and the
    // ~26-40k-token context reload.
    const total = Number(/[^-]total=(\d+)ms/.exec(round[0])[1]);
    const cliTotal = Number(/cli-total=(-?\d+)ms/.exec(round[0])[1]);
    assert.ok(total > 0, 'the wall clock must be a real measurement');
    if (cliTotal > 0) {
      assert.ok(
        total >= cliTotal,
        `the wall clock must be at least the CLI's own figure: total=${total} cli-total=${cliTotal}`
      );
      console.log(`[v43 evidence] transport cost: wall=${total}ms cli=${cliTotal}ms delta=${total - cliTotal}ms`);
    }
    await vscode.commands.executeCommand('notifications.clearAll');
  });

  test('the CLI ran in the product-owned neutral cwd, and what it left behind is recorded', async function () {
    if (!LIVE) {
      this.skip();
    }
    this.timeout(30000);
    // The directory the wiring creates. Its location is a contract, not a
    // detail: spawning in the workspace would pull the user's CLAUDE.md, their
    // auto-memory and their project MCP servers into a generation the context
    // panel never showed.
    const guess = path.join(os.homedir(), '.config', 'Code', 'User', 'globalStorage');
    const candidates = [];
    const walk = (dir, depth) => {
      if (depth > 2) {
        return;
      }
      let entries = [];
      try {
        entries = fs.readdirSync(dir, { withFileTypes: true });
      } catch {
        return;
      }
      for (const e of entries) {
        if (!e.isDirectory()) {
          continue;
        }
        if (e.name === 'claude-cwd') {
          candidates.push(path.join(dir, e.name));
        } else if (depth < 2) {
          walk(path.join(dir, e.name), depth + 1);
        }
      }
    };
    walk(guess, 0);
    // vscode-test runs with its own user-data-dir, so the storage root may sit
    // elsewhere; the assertion that matters is the NEGATIVE one below, which
    // does not depend on finding it.
    for (const dir of candidates) {
      const left = fs.readdirSync(dir);
      console.log(`[v43 evidence] neutral cwd ${dir} holds: ${JSON.stringify(left)}`);
      assert.ok(
        !left.includes('CLAUDE.md'),
        `the CLI wrote a CLAUDE.md into its own cwd, which would load as project context into every later generation (scraps S43-5): ${dir}`
      );
    }
    // The invariant that does not depend on locating the storage dir: the CLI
    // must not have run in, or written to, the user's workspace.
    assert.ok(
      !fs.existsSync(path.join(repo, '.claude')),
      'the CLI must never have run in the workspace: a .claude directory appeared there'
    );
    if (candidates.length === 0) {
      console.log('[v43 evidence] neutral cwd not located under the default storage root (vscode-test uses its own user-data-dir); the workspace-negative assertion above is the contract that does not depend on finding it');
    }
  });
});
